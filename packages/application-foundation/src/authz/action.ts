import type { NodePgDatabase } from 'drizzle-orm/node-postgres';
import type { z } from 'zod';
import { writeAudit, type AuditOutcome } from '../audit/audit.js';
import type { Auth } from '../auth/auth.js';
import { getPrincipal, type Principal } from '../auth/principal.js';
import type { OrgId } from '../tenancy/ids.js';
import { withTenant, withUser, type TenantTx } from '../tenancy/with-tenant.js';
import { OrgError } from '../orgs/errors.js';
import { requireMembership, type Caller } from '../orgs/orgs.js';
import { can, USER_PERMISSIONS, type Authz, type UserPermission } from './policy.js';

type Db = NodePgDatabase<Record<string, unknown>>;

/** Error codes an action returns. Same names as contract C4 `ErrorCode`. */
export type ActionErrorCode =
  'unauthenticated' | 'forbidden' | 'not_found' | 'validation_failed' | 'conflict';

/** Expected failure thrown by a handler. Rolls back the handler's writes. */
export class ActionError extends Error {
  readonly code: ActionErrorCode;
  constructor(code: ActionErrorCode, message: string, options?: { cause?: unknown }) {
    super(message, options);
    this.name = 'ActionError';
    this.code = code;
  }
}

export type ActionResult<T> =
  | { readonly ok: true; readonly value: T }
  | { readonly ok: false; readonly code: ActionErrorCode; readonly message: string };

export interface ActionDeps {
  readonly db: Db;
  readonly auth: Auth;
}

/** One request. Nothing here is trusted except what `getPrincipal` derives from the session cookie. */
export interface ActionRequest {
  readonly headers: Headers;
  readonly input: unknown;
  /** UUID generated by the server for this request, never taken from the client. */
  readonly requestId: string;
}

export interface OrgActionContext {
  readonly tx: TenantTx;
  readonly principal: Principal;
  /** The session's active org, after the membership check. Never request input. */
  readonly orgId: OrgId;
  readonly membership: { readonly id: string; readonly role: string };
  readonly caller: Caller;
}

export interface UserActionContext {
  readonly db: Db;
  readonly principal: Principal;
  readonly caller: Caller & { readonly sessionId: string };
}

export interface Action<T> {
  (deps: ActionDeps, request: ActionRequest): Promise<ActionResult<T>>;
  readonly permission: string;
  readonly scope: 'org' | 'user';
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const fail = <T>(code: ActionErrorCode, message: string): ActionResult<T> => ({
  ok: false,
  code,
  message,
});

function validationMessage(error: z.ZodError): string {
  const paths = [...new Set(error.issues.map((i) => i.path.join('.') || '(input)'))];
  return `invalid input: ${paths.slice(0, 10).join(', ')}`;
}

/** Maps an expected handler failure to a result. Anything else is a programmer error: null. */
function expected(error: unknown): { code: ActionErrorCode; message: string } | null {
  if (error instanceof ActionError) return { code: error.code, message: error.message };
  if (error instanceof OrgError) {
    return {
      code: error.code === 'last_owner' ? 'conflict' : error.code,
      message: error.message,
    };
  }
  return null;
}

async function readPrincipal(deps: ActionDeps, headers: Headers): Promise<Principal | null> {
  try {
    return await getPrincipal(deps.auth, headers);
  } catch {
    // A session that cannot be read is no session: deny, never grant.
    return null;
  }
}

/** Audit for a request with no org context (unauthenticated, or no active org). */
async function auditWithoutOrg(
  db: Db,
  principal: Principal | null,
  event: { action: string; resourceType: string; outcome: AuditOutcome; requestId: string },
): Promise<void> {
  const record = { ...event, actorId: principal?.userId ?? null, orgId: null, resourceId: null };
  if (principal) {
    await withUser(db, principal.userId, (tx) => writeAudit(tx, record));
  } else {
    await db.transaction((tx) => writeAudit(tx, record));
  }
}

function checkRequestId(requestId: string): void {
  if (!UUID.test(requestId)) throw new Error('requestId must be a server-generated UUID');
}

/**
 * Wraps an org-scoped route or server action (task P1-05). Every request runs,
 * in this order and in one transaction for steps 3 to 7:
 *
 * 1. authenticate: `getPrincipal`; none → `unauthenticated`
 * 2. active org from the session; none → `forbidden`
 * 3. membership in that org, re-checked now; none → `not_found`
 * 4. `can(role, permission)`; no → `forbidden`
 * 5. parse `input` with the schema; invalid → `validation_failed`
 * 6. `handler` inside `withTenant(activeOrg)`
 * 7. audit event for the outcome
 *
 * Denials (1 to 4) are audited and committed; the handler never runs. If the
 * handler throws, its writes roll back and a failure event is written instead.
 * `permission` is required and must be declared in `authz`: a missing or unknown
 * permission fails typecheck, and is rejected again here at startup.
 */
export function defineAction<P extends string, S extends z.ZodType, T>(
  authz: Authz<P>,
  config: {
    readonly permission: NoInfer<P>;
    readonly input: S;
    /** Audit action name. Default: the permission. */
    readonly action?: string;
    readonly resourceType: string;
    /** Id of the resource the action touched, for the audit event. */
    readonly resourceId?: (result: T, input: z.output<S>) => string | null;
    readonly handler: (ctx: OrgActionContext, input: z.output<S>) => Promise<T>;
  },
): Action<T> {
  if (!authz.permissions.includes(config.permission)) {
    throw new Error(`defineAction: permission ${String(config.permission)} is not declared`);
  }
  const action = config.action ?? config.permission;
  const base = { action, resourceType: config.resourceType };

  const run = async (deps: ActionDeps, request: ActionRequest): Promise<ActionResult<T>> => {
    checkRequestId(request.requestId);
    const requestId = request.requestId;

    const principal = await readPrincipal(deps, request.headers);
    if (!principal) {
      await auditWithoutOrg(deps.db, null, { ...base, outcome: 'denied', requestId });
      return fail('unauthenticated', 'sign in required');
    }
    const orgId = principal.activeOrgId;
    if (!orgId) {
      await auditWithoutOrg(deps.db, principal, { ...base, outcome: 'denied', requestId });
      return fail('forbidden', 'no active organization');
    }
    const caller: Caller = { userId: principal.userId, requestId };
    const audit = (tx: TenantTx, outcome: AuditOutcome, resourceId: string | null = null) =>
      writeAudit(tx, { ...base, actorId: principal.userId, orgId, resourceId, outcome, requestId });

    try {
      return await withTenant(deps.db, orgId, async (tx): Promise<ActionResult<T>> => {
        let membership: { id: string; role: string };
        try {
          membership = await requireMembership(tx, orgId, principal.userId);
        } catch (error) {
          if (!(error instanceof OrgError)) throw error;
          await audit(tx, 'denied');
          return fail('not_found', 'not found');
        }
        if (!can(authz, membership.role, config.permission)) {
          await audit(tx, 'denied');
          return fail('forbidden', 'not allowed');
        }
        const parsed = config.input.safeParse(request.input);
        if (!parsed.success) return fail('validation_failed', validationMessage(parsed.error));

        const value = await config.handler(
          { tx, principal, orgId, membership, caller },
          parsed.data as z.output<S>,
        );
        await audit(tx, 'success', config.resourceId?.(value, parsed.data as z.output<S>) ?? null);
        return { ok: true, value };
      });
    } catch (error) {
      // The handler's transaction rolled back. Record the outcome separately.
      const known = expected(error);
      await withTenant(deps.db, orgId, (tx) =>
        audit(tx, known?.code === 'forbidden' ? 'denied' : 'failure'),
      );
      if (known) return fail(known.code, known.message);
      throw error;
    }
  };

  return Object.assign(run, { permission: config.permission as string, scope: 'org' as const });
}

/**
 * Wraps a route that needs a signed-in user but no active org (C4 v1.1
 * `getMe`, `setActiveOrg`; creating an org; accepting an invitation). The
 * permission must be one of `USER_PERMISSIONS`, which every signed-in user has.
 *
 * The handler gets the database, not a transaction, because these operations
 * span orgs; each must open its own transaction and audit its change in it (the
 * P1-04 operations do). Denials and failures are audited here.
 */
export function defineUserAction<S extends z.ZodType, T>(config: {
  readonly permission: UserPermission;
  readonly input: S;
  readonly action?: string;
  readonly resourceType: string;
  readonly handler: (ctx: UserActionContext, input: z.output<S>) => Promise<T>;
}): Action<T> {
  if (!(USER_PERMISSIONS as readonly string[]).includes(config.permission)) {
    throw new Error(`defineUserAction: ${String(config.permission)} is not a user permission`);
  }
  const base = { action: config.action ?? config.permission, resourceType: config.resourceType };

  const run = async (deps: ActionDeps, request: ActionRequest): Promise<ActionResult<T>> => {
    checkRequestId(request.requestId);
    const requestId = request.requestId;
    const principal = await readPrincipal(deps, request.headers);
    if (!principal) {
      await auditWithoutOrg(deps.db, null, { ...base, outcome: 'denied', requestId });
      return fail('unauthenticated', 'sign in required');
    }
    const parsed = config.input.safeParse(request.input);
    if (!parsed.success) return fail('validation_failed', validationMessage(parsed.error));
    try {
      const value = await config.handler(
        {
          db: deps.db,
          principal,
          caller: { userId: principal.userId, requestId, sessionId: principal.sessionId },
        },
        parsed.data as z.output<S>,
      );
      return { ok: true, value };
    } catch (error) {
      const known = expected(error);
      await auditWithoutOrg(deps.db, principal, {
        ...base,
        outcome: known?.code === 'forbidden' ? 'denied' : 'failure',
        requestId,
      });
      if (known) return fail(known.code, known.message);
      throw error;
    }
  };

  return Object.assign(run, { permission: config.permission as string, scope: 'user' as const });
}
